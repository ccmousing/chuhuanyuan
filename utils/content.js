const byId = {};
ARTICLES.forEach(function (a) { byId[a.id] = a; });

function getArticle(id) { return byId[id] || null; }

/** 取文章列表；传 ids 则按 ids 顺序取，不传则返回全部 */
function listArticles(ids) {
  if (!ids) return ARTICLES.slice();
  return ids.map(function (i) { return byId[i]; }).filter(Boolean);
}

/** 把 sections 展平成纯文本数组（供搜索、字数统计、分享摘要用） */
function plainParagraphs(a) {
  if (!a) return [];
  if (a.sections) {
    const out = [];
    a.sections.forEach(function (s) {
      if (s.h) out.push(s.h);
      (s.p || []).forEach(function (t) { out.push(t); });
    });
    return out;
  }
  return a.paras || [];
}

/** 正文字数（不含小标题，用于阅读时长估算） */
function wordCount(a) {
  if (!a) return 0;
  if (a.sections) {
    return a.sections.reduce(function (n, s) {
      return n + (s.p || []).join('').length;
    }, 0);
  }
  return (a.paras || []).join('').length;
}

