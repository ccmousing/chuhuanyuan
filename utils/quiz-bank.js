const DIFF_NAME = { 1: '入门', 2: '进阶', 3: '挑战' };
const ALL_LETTERS = ['A', 'B', 'C', 'D'];

// 每轮题量与各档抽题数：入门 4 + 进阶 4 + 挑战 2 = 10 题
const MIX = [{ lv: 1, n: 4 }, { lv: 2, n: 4 }, { lv: 3, n: 2 }];
const ROUND_SIZE = MIX.reduce(function (n, m) { return n + m.n; }, 0);

/** 按题目选项数取字母表，这样以后加四选一题目不用改代码 */
function lettersOf(len) { return ALL_LETTERS.slice(0, len); }

/**
 * 抽一轮题。
 * @param {number} roundNo 轮次（由「已答题数 ÷ 每轮题量」推导，不额外存状态）
 * 同一 roundNo 结果固定 —— 中途退出再进不会换题；答满一轮后自动换一批。
 */
function pickRound(roundNo) {
  const picked = [];
  MIX.forEach(function (m) {
    const pool = QUIZ.filter(function (q) { return q.lv === m.lv; });
    for (let i = 0; i < Math.min(m.n, pool.length); i++) {
      picked.push(pool[(roundNo * 3 + i) % pool.length]);
    }
  });
  return picked;
}


/**
 * 只从指定的题目 id 里抽题（错题重练用）。
 * @param {number[]} idList 题目 id 列表
 * @param {number} [limit] 最多抽几道；不传则全出
 */
function pickByIds(idList, limit) {
  const pool = QUIZ.filter(function (q) { return idList.indexOf(q.id) > -1; });
  return limit ? pool.slice(0, limit) : pool;
}

