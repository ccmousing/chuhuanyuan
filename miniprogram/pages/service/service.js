//
// 这里刻意不放任何编造的经营数据（原来写的「已服务 260+ 家庭」「3 个工作日出片」已删除）——
// 未开放的功能配上好看的假数字，比空着更容易误导人。

// 开放原因说明提到两处：本页说明条、点击按钮的弹窗。文案集中在这里，避免两处不一致。
const REASON = '预约撮合属经营性功能，个人主体小程序不予开放，需先注册个体工商户或企业主体。';

Page({
  data: {
    cur: 0,
    cats: ['全部', '仪式操办', '司仪', '用品', '旅拍', '场地'],

    // 仅为「界面形态示意」：描述的是服务类型，不含商家名称与经营数据
    services: [
      { icon: '🎎', title: '仪式操办 · 全套流程指导', sub: '含司仪、流程安排与用品清单', bg: 'rgba(200,68,60,.1)' },
      { icon: '🪵', title: '红皮木屐 · 手工定制', sub: '可刻名字 · 支持寄送海外', bg: 'rgba(201,160,85,.15)' },
      { icon: '📷', title: '出花园纪实旅拍', sub: '仪式跟拍 + 全家福', bg: 'rgba(63,140,118,.13)' },
      { icon: '🏛', title: '集体成人礼 · 活动报名', sub: '与文化馆等机构联合举办', bg: 'rgba(120,110,200,.13)' }
    ]
  },

  onCat(e) {
    // 分类切换只是浏览行为，不具欺骗性，保留交互；
    // 真正的「预约」动作走 onPlanTap 如实说明。
    this.setData({ cur: Number(e.currentTarget.dataset.i) });
  },

  /** 点击「规划中」按钮：如实说明原因，而不是毫无反应 */
  onPlanTap(e) {
    const t = e.currentTarget.dataset.t || '该服务';
    wx.showModal({
      title: '尚未开放预约',
      content: t + '：' + REASON + '\n\n开放前还需完成商家资质人工审核、投诉与退款处理机制。',
      showCancel: false,
      confirmText: '知道了'
    });
  },

  onShareAppMessage() {
    // 分享语只描述产品，不承诺未开放的功能
    return { title: '出花园 · 潮汕人的十五岁成人礼', path: '/pages/index/index' };
  }
});
